package v1alpha1

import (
	corev1 "k8s.io/api/core/v1"
	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// CasdoorApplicationSpec describes an application. Fields other than casdoorRef, name,
// deletionPolicy, clientSecretSecretRef, credentialsSecretName and extraFields keep the names
// of the Casdoor API, and only the fields that are set are written.
type CasdoorApplicationSpec struct {
	CasdoorRef CasdoorReference `json:"casdoorRef"`

	// Name of the application in Casdoor. Defaults to the name of this object.
	// +kubebuilder:validation:XValidation:rule="self == oldSelf",message="name is immutable"
	// +optional
	Name string `json:"name,omitempty"`

	// DeletionPolicy decides whether deleting this object deletes the application in Casdoor.
	// +kubebuilder:validation:Enum=Delete;Retain
	// +kubebuilder:default=Delete
	// +optional
	DeletionPolicy string `json:"deletionPolicy,omitempty"`

	// Organization the users of this application belong to.
	// +kubebuilder:validation:MinLength=1
	Organization string `json:"organization"`

	// +optional
	DisplayName string `json:"displayName,omitempty"`

	// +optional
	Logo string `json:"logo,omitempty"`

	// +optional
	HomepageUrl string `json:"homepageUrl,omitempty"`

	// +optional
	Description string `json:"description,omitempty"`

	// +optional
	RedirectUris []string `json:"redirectUris,omitempty"`

	// +optional
	GrantTypes []string `json:"grantTypes,omitempty"`

	// +kubebuilder:validation:Enum=JWT;JWT-Empty;JWT-Custom;JWT-Standard
	// +optional
	TokenFormat string `json:"tokenFormat,omitempty"`

	// +kubebuilder:validation:Minimum=1
	// +optional
	ExpireInHours *int32 `json:"expireInHours,omitempty"`

	// +kubebuilder:validation:Minimum=1
	// +optional
	RefreshExpireInHours *int32 `json:"refreshExpireInHours,omitempty"`

	// Cert is the name of the certificate that signs the tokens.
	// +optional
	Cert string `json:"cert,omitempty"`

	// +optional
	EnablePassword *bool `json:"enablePassword,omitempty"`

	// +optional
	EnableSignUp *bool `json:"enableSignUp,omitempty"`

	// ClientId is generated by Casdoor when empty.
	// +optional
	ClientId string `json:"clientId,omitempty"`

	// ClientSecretSecretRef sets the client secret. Casdoor generates one when it is empty.
	// +optional
	ClientSecretSecretRef *corev1.SecretKeySelector `json:"clientSecretSecretRef,omitempty"`

	// CredentialsSecretName is the Secret the operator writes endpoint, clientId, clientSecret,
	// organizationName, applicationName and certificate to. Defaults to <name>-casdoor.
	// +optional
	CredentialsSecretName string `json:"credentialsSecretName,omitempty"`

	// ExtraFields sets any other field of the Casdoor application, e.g. signinMethods or providers.
	// +optional
	ExtraFields map[string]apiextensionsv1.JSON `json:"extraFields,omitempty"`
}

type CasdoorApplicationStatus struct {
	// +optional
	ObservedGeneration int64 `json:"observedGeneration,omitempty"`

	// +optional
	ClientId string `json:"clientId,omitempty"`

	// +optional
	CredentialsSecretName string `json:"credentialsSecretName,omitempty"`

	// +listType=map
	// +listMapKey=type
	// +optional
	Conditions []metav1.Condition `json:"conditions,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:shortName=casdoorapp
// +kubebuilder:printcolumn:name="Casdoor",type=string,JSONPath=`.spec.casdoorRef.name`
// +kubebuilder:printcolumn:name="Organization",type=string,JSONPath=`.spec.organization`
// +kubebuilder:printcolumn:name="Client ID",type=string,JSONPath=`.status.clientId`
// +kubebuilder:printcolumn:name="Ready",type=string,JSONPath=`.status.conditions[?(@.type=="Ready")].status`
// +kubebuilder:printcolumn:name="Age",type=date,JSONPath=`.metadata.creationTimestamp`

// CasdoorApplication is an application in a Casdoor server.
type CasdoorApplication struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   CasdoorApplicationSpec   `json:"spec"`
	Status CasdoorApplicationStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true

type CasdoorApplicationList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []CasdoorApplication `json:"items"`
}

func init() {
	SchemeBuilder.Register(&CasdoorApplication{}, &CasdoorApplicationList{})
}
